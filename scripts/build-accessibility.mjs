import { build } from "esbuild";
import { writeFile } from "node:fs/promises";
const result = await build({
  entryPoints: ["src/scanner/evidence/browser-entry.ts"],
  bundle: true,
  format: "iife",
  globalName: "BuggdEvidence",
  platform: "browser",
  target: "es2022",
  write: false,
  legalComments: "inline",
});
await writeFile(
  "src/scanner/evidence/browser-source.ts",
  `// Generated by scripts/build-accessibility.mjs; do not edit.\nexport const evidenceScript = ${JSON.stringify(result.outputFiles[0].text)};\n`,
);
